    with open(ipynb_path, 'w', encoding='utf-8') as f:
        json.dump(nb, f, indent=1, ensure_ascii=False)
    
    print(f"✅ 已成功更新 {os.path.basename(ipynb_path)} 的第 {target_cell_index} 個儲存格。")

