def update_notebook():
    if not os.path.exists(ipynb_path):
        print(f"❌ 找不到目標檔案: {ipynb_path}")
        return

    with open(ipynb_path, 'r', encoding='utf-8') as f:
        nb = json.load(f)

    if target_cell_index >= len(nb['cells']):
        print(f"❌ 索引 {target_cell_index} 超出範圍 (總長度 {len(nb['cells'])})")
        return

    # 執行覆寫
